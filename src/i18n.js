export function resolveLocale(preferences = []) {
  for (const preference of preferences) {
    const base = preference.toLowerCase().split("-")[0];
    const lang = base === "zh" ? "zh-hans" : base;
    if (languages[lang]) return lang;
  }
  return "en";
}

