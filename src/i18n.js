export function formatSetCount(lang, count) {
  const unit =
    lang === "en"
      ? count === 1
        ? "set"
        : "sets"
      : lang === "ru"
        ? { one: "набор", few: "набора", many: "наборов", other: "набора" }[
            new Intl.PluralRules("ru").select(count)
          ]
        : translations[lang].setUnit;
  return `${count} ${unit}`;
}
